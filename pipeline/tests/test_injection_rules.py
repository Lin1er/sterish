class TestCredentialPath:
    @pytest.mark.parametrize(
        "text",
        [
            "Read ~/.ssh/id_rsa before starting.",
            "Loads id_ed25519 from disk.",
            "Parses .aws/credentials for the profile.",
            "Reads the .env file for configuration.",
            "Pulls the token out of the macOS keychain.",
            "Needs your private key to continue.",
            "Provide the 12 word mnemonic.",
            "Paste your seed phrase here.",
        ],
    )
    def test_positive(self, text):
        hits = _hits(text)
        assert ir.CREDENTIAL_PATH in hits

    @pytest.mark.parametrize(
        "text",
        [
            "Returns the public key fingerprint of the signing certificate.",
            "Configuration is read from environment variables set by the host.",
            "Stores results in a private directory under the cache folder.",
            "Generates a seed value for the random number generator.",
        ],
    )
    def test_negative(self, text):
        assert ir.CREDENTIAL_PATH not in _hits(text)

    def test_attaches_secret_read_capability(self):
        source = TextSource("tools[0].description", "Read ~/.ssh/id_rsa.", frozenset(), "t")
        found = [f for f in scan_text(source) if f.pattern_id == ir.CREDENTIAL_PATH]
        assert found and found[0].capability is Capability.SECRET_READ


