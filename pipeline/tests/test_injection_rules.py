# undeclared_capability -- the detector that closes the gap
# --------------------------------------------------------------------------------------
class TestUndeclaredCapability:
    @pytest.mark.parametrize(
        "text,capability",
        [
            ("Loads the user private key before signing.", Capability.SECRET_READ),
            ("Reads the .env file at startup.", Capability.ENV_READ),
            ("Reads the contents of every file in the folder.", Capability.FILE_READ),
            ("Writes the summary to a file next to the input.", Capability.FILE_WRITE),
            ("Posts the result to https://drop.example.xyz/x", Capability.NETWORK_OUTBOUND),
            ("Opens the user wallet to sign.", Capability.WALLET_ACCESS),
        ],
    )
    def test_positive(self, text, capability):
        source = TextSource("tools[0].description", text, frozenset(), "do_thing")
        found = [f for f in scan_text(source) if f.pattern_id == ir.UNDECLARED_CAPABILITY]
        assert capability in {f.capability for f in found}

    @pytest.mark.parametrize(
        "text,declared",
        [
            ("Reads the .env file at startup.", {Capability.ENV_READ}),
            ("Reads the contents of every file in the folder.", {Capability.FILE_READ}),
            ("Posts the result to the declared endpoint api.", {Capability.NETWORK_OUTBOUND}),
            ("Opens the user wallet to sign.", {Capability.WALLET_ACCESS}),
        ],
    )
    def test_negative_when_declared(self, text, declared):
        source = TextSource("tools[0].description", text, frozenset(declared), "do_thing")
        found = [
            f
            for f in scan_text(source)
            if f.pattern_id == ir.UNDECLARED_CAPABILITY and f.capability in declared
        ]
        assert not found

    def test_negation_is_not_a_capability(self):
        source = TextSource(
            "tools[0].description",
            "Returns a forecast. It reads no local files and needs no api key.",
            frozenset(),
            "get_forecast",
        )
        found = [f for f in scan_text(source) if f.pattern_id == ir.UNDECLARED_CAPABILITY]
        assert not found

    def test_negation_does_not_excuse_a_credential_path(self):
        # Critical detectors stay literal on purpose: "never read ~/.ssh/id_rsa" still names
        # the file, and a benign skill has no reason to.
        source = TextSource("f", "This tool will never read ~/.ssh/id_rsa.", frozenset(), None)
        assert ir.CREDENTIAL_PATH in {f.pattern_id for f in scan_text(source)}

    def test_severity_is_high(self):
        source = TextSource("f", "Loads the user private key.", frozenset(), None)
        found = [f for f in scan_text(source) if f.pattern_id == ir.UNDECLARED_CAPABILITY]
        assert all(f.severity is Severity.HIGH for f in found)


