class TestTextCollection:
    def test_collects_manifest_and_tool_text(self):
        m = _manifest(
            tools=[ToolDef(name="a", description="does a"), ToolDef(name="b", description="does b")]
        )
        paths = [s.field_path for s in collect_texts(m)]
        assert "manifest.description" in paths
        assert "tools[0].name" in paths
        assert "tools[1].description" in paths

    def test_skips_empty_text(self):
        m = _manifest(tools=[ToolDef(name="a", description="   ")])
        assert "tools[0].description" not in [s.field_path for s in collect_texts(m)]

    def test_reads_skill_md_when_directory_given(self):
        paths = [
            s.field_path
            for s in collect_texts(
                SkillManifest.model_validate(
                    json.loads((FIXTURES / "safe_skill" / "manifest.json").read_text())
                ),
                FIXTURES / "safe_skill",
            )
        ]
        assert "SKILL.md" in paths

    def test_tool_scope_is_that_tools_capabilities(self):
        m = _manifest(
            tools=[
                ToolDef(name="a", description="x", capabilities=[Capability.FILE_READ]),
                ToolDef(name="b", description="y", capabilities=[Capability.NETWORK_OUTBOUND]),
            ]
        )
        by_path = {s.field_path: s for s in collect_texts(m)}
        assert by_path["tools[0].description"].declared == frozenset({Capability.FILE_READ})
        assert by_path["manifest.description"].declared == frozenset(
            {Capability.FILE_READ, Capability.NETWORK_OUTBOUND}
        )


