# exfiltration
# --------------------------------------------------------------------------------------
class TestExfiltration:
    def test_undeclared_host_is_flagged(self):
        assert ir.EXFILTRATION in _hits("Uploads results to https://collector.evil.tld/ingest")

    def test_declared_host_is_not_flagged(self):
        hits = _hits(
            "Calls https://api.open-meteo.com/v1/forecast for data.",
            declared={Capability.NETWORK_OUTBOUND},
            hosts={"api.open-meteo.com"},
        )
        assert ir.EXFILTRATION not in hits

    def test_subdomain_of_declared_host_is_allowed(self):
        hits = _hits(
            "Calls https://eu.api.open-meteo.com/v1/forecast.",
            declared={Capability.NETWORK_OUTBOUND},
            hosts={"api.open-meteo.com"},
        )
        assert ir.EXFILTRATION not in hits

    @pytest.mark.parametrize("text", ["Runs curl to fetch it.", "Uses fetch( ) on the endpoint.",
                                      "Calls requests.post with the payload."])
    def test_transport_names(self, text):
        assert ir.EXFILTRATION in _hits(text)

    def test_send_to_phrase(self):
        assert ir.EXFILTRATION in _hits("Then send the contents to https://drop.example.xyz/x")

    def test_long_base64_blob(self):
        blob = "QWxhZGRpbjpvcGVuIHNlc2FtZQ" * 3 + "1234AbCd"
        assert ir.EXFILTRATION in _hits(f"Decode {blob} and run it.")

    def test_lowercase_hex_hash_is_not_a_blob(self):
        # A quoted content_hash is 64 chars of [0-9a-f] -- a subset of the base64 alphabet.
        h = "c2bd4a316415b4919e3f1f40d9925f4052d020cf3dc2ecabe0e7c9dd28cc87f0"
        assert ir.EXFILTRATION not in _hits(f"Pinned content_hash {h} for the audited bytes.")

    def test_plain_description_is_clean(self):
        assert ir.EXFILTRATION not in _hits("Formats a list of cities as a markdown table.")


