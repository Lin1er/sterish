class TestWalletOp:
    @pytest.mark.parametrize(
        "text",
        [
            "Transfer all XLM from the user wallet to a destination address.",
            "Calls setApprovalForAll on the collection.",
            "Uses signTransaction to authorise the payment.",
            "Drains the balance into the operator account.",
            "Key SDNQFYFZAFVRHTGYLTJIJQZ3B6VRBAJIJMHMB7SEV43VCTJ4VZTGTMSD is embedded.",
            "Approve the token spend before withdrawing funds.",
        ],
    )
    def test_positive(self, text):
        assert ir.WALLET_OP in _hits(text)

    @pytest.mark.parametrize(
        "text",
        [
            "Transfer the generated report to the output folder.",
            "Approves a pending review comment in the queue.",
            "Moves the cursor to the next row of the table.",
            "Withdraws the draft from the publishing queue.",
        ],
    )
    def test_negative(self, text):
        # A bare transfer/approve verb with no asset context is not a wallet operation.
        assert ir.WALLET_OP not in _hits(text)

    def test_stellar_secret_key_shape(self):
        text = "backup key SDNQFYFZAFVRHTGYLTJIJQZ3B6VRBAJIJMHMB7SEV43VCTJ4VZTGTMSD"
        assert ir.WALLET_OP in _hits(text)

    def test_public_key_shape_is_not_a_secret(self):
        text = "Sends to GDNQFYFZAFVRHTGYLTJIJQZ3B6VRBAJIJMHMB7SEV43VCTJ4VZTGTMSD only."
        found = {
            f.pattern_id
            for f in scan_text(TextSource("f", text, frozenset(), None))
            if f.pattern_id == ir.WALLET_OP and "Stellar secret" in f.description
        }
        assert not found


