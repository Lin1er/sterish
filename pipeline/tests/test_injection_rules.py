"""One positive and one negative test per detector in injection_rules.

The negatives carry as much weight as the positives here. A scanner that flags every skill is
not a scanner, it is a "no" button: if benign prose trips it, operators learn to ignore the
verdict and the audit stops meaning anything.
"""

import json
from pathlib import Path

import pytest

from sterish_pipeline.models import Capability, Severity, SkillManifest, ToolDef
from sterish_pipeline.stages import injection_rules as ir
from sterish_pipeline.stages.injection_rules import (
    TextSource,
    collect_texts,
    declared_hosts,
    scan_injection,
    scan_text,
)

FIXTURES = Path(__file__).parent / "fixtures"


def _hits(text: str, declared: set[Capability] | None = None, hosts: set[str] | None = None,
          field_path: str = "tools[0].description", tool_name: str | None = "do_thing") -> set[str]:
    source = TextSource(field_path, text, frozenset(declared or set()), tool_name)
    return {f.pattern_id for f in scan_text(source, hosts or set())}


def _manifest(**kw) -> SkillManifest:
    base = dict(
        skill_id="com.example.skill",
        name="Example",
        description="An example skill.",
        version="1.0.0",
        permissions=[],
        tools=[],
    )
    base.update(kw)
    return SkillManifest(**base)


